package com.fpe.entity.characters;

import java.util.List;

import com.fpe.entity.Ability;
import com.fpe.entity.FpeCombat;
import com.fpe.entity.FpeEntity;
import com.fpe.entity.FpeFx;
import com.fpe.entity.FpeProjectile;
import com.fpe.entity.FpeUtil;

import net.minecraft.core.particles.ParticleTypes;
import net.minecraft.sounds.SoundEvent;
import net.minecraft.sounds.SoundEvents;
import net.minecraft.world.damagesource.DamageSource;
import net.minecraft.world.effect.MobEffectInstance;
import net.minecraft.world.effect.MobEffects;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.entity.LivingEntity;
import net.minecraft.world.entity.ai.attributes.AttributeSupplier;
import net.minecraft.world.level.Level;
import net.minecraft.world.phys.Vec3;

/**
 * Red Circle = DANGER AU Miss Circle, "pyromaniac" (docs/ref/confirmed/red_circle.jpg): slim, purple-black floor-length hair,
 * black wolf-ear hat with an orange band over the eyes, shark grin, orange fringed poncho, bandaged right forearm with a black
 * claw glove, strapped boots and a hand-held FLAMETHROWER in the left hand.
 * Model + animations: assets/fpe/bbmodels/red_circle.bbmodel (generated by tools/bbgen/chars/red_circle.py); ticks below = hit frames.
 */
public class RedCircle extends FpeEntity {
    public RedCircle(EntityType<? extends FpeEntity> type, Level level) { super(type, level); }

    @Override public Faction faction() { return Faction.DANGER; }

    public static AttributeSupplier.Builder attributes() { return baseAttributes(170, 8, 0.31, 5, 0.5); }

    @Override public double preferredDistance() { return 4.0; }
    @Override protected int restTicks() { return isEnraged() ? 6 : 14; }
    @Override public boolean fireImmune() { return true; }
    @Override protected SoundEvent getHurtSound(DamageSource s) { return SoundEvents.PLAYER_HURT_ON_FIRE; }
    @Override protected SoundEvent getDeathSound() { return SoundEvents.BLAZE_DEATH; }
    @Override protected SoundEvent getAmbientSound() { return SoundEvents.BLAZE_AMBIENT; }

    /** flamethrower nozzle (held in the LEFT hand, aimed forward at chest height) */
    static Vec3 nozzle(FpeEntity e, double fwd) {
        return e.position().add(0, 1.4, 0).add(FpeUtil.forward(e).scale(fwd)).add(FpeUtil.right(e).scale(-0.3));
    }

    static void burnCone(FpeEntity e, double range, double half, float dmg, int secs) {
        for (LivingEntity v : FpeCombat.cone(e, range, half)) if (FpeUtil.hit(e, v, dmg, 0.2, 0.05)) v.setSecondsOnFire(secs);
    }

    static void burnRadius(FpeEntity e, Vec3 c, double r, float dmg, double kb, int secs) {
        for (LivingEntity v : FpeUtil.enemiesInRadius(e, c, r, 2.5, 1)) if (FpeUtil.hit(e, v, dmg, kb, 0.4)) v.setSecondsOnFire(secs);
    }

    /** a jet of flame particles from the nozzle along dir */
    static void jet(FpeEntity e, Vec3 from, Vec3 dir, double len) {
        for (int i = 1; i <= 4; i++) {
            double d = len * i / 4.0;
            FpeUtil.particles(e, ParticleTypes.FLAME, from.add(dir.scale(d)), 3, 0.15 + i * 0.1, 0.15 + i * 0.08, 0.15 + i * 0.1, 0.02);
        }
        FpeUtil.particles(e, ParticleTypes.SMOKE, from.add(dir.scale(len + 0.6)), 2, 0.4, 0.3, 0.4, 0.02);
    }

    static Vec3 yawDir(FpeEntity e, double offDeg) { return FpeCombat.rotY(FpeUtil.forward(e), offDeg); }

    @Override
    protected void registerAbilities(List<Ability> out) {
        // 1. sustained flamethrower spray, sweeping left/right (anim sweep peaks 14/22/30/38/46)
        out.add(Ability.of("flame_stream", 58, 70).range(1.5, 9).weight(5).faceUntil(46).tick((e, t, tk) -> {
            if (tk >= 14 && tk <= 46) {
                jet(e, nozzle(e, 1.4), FpeUtil.forward(e), 6.5);
                if (tk % 3 == 0) FpeUtil.sound(e, SoundEvents.BLAZE_SHOOT, 0.5f, 0.7f);
                if (tk % 4 == 2) burnCone(e, 8, 26, e.dmg(0.4f), 4);
            }
        }));
        // 2. fireball blast from the nozzle (15; enraged also 19 + 23)
        out.add(Ability.of("fireball", 34, 60).range(5, 22).weight(4).faceUntil(15).tick((e, t, tk) -> {
            if (tk == 15 || (e.isEnraged() && (tk == 19 || tk == 23))) {
                Vec3 from = nozzle(e, 1.6);
                FpeUtil.projectile(e, FpeProjectile.Kind.FIREBALL, from, FpeUtil.aim(from, t, 1.0, 0.4), e.dmg(1.5f));
                FpeUtil.sound(e, SoundEvents.FIRECHARGE_USE, 1f, 0.8f);
                FpeUtil.particles(e, ParticleTypes.FLAME, from, 14, 0.2, 0.2, 0.2, 0.08);
            }
        }));
        // 3. crouch and blast the nozzle into the ground: fire ring (17)
        out.add(Ability.of("flame_burst", 40, 90).range(0, 5.5).weight(3).faceUntil(10).tick((e, t, tk) -> {
            if (tk == 17) {
                burnRadius(e, e.position(), 5.5, e.dmg(1.3f), 1.5, 5);
                FpeUtil.fx(e, FpeFx.Kind.RING_SHOCK, e.position().add(0, 0.1, 0), 0, 14, 6.5f, 0).color(0xFFFF8020);
                FpeUtil.arc(e, ParticleTypes.FLAME, e.position().add(0, 0.3, 0), 0, 180, 3, 40);
                FpeUtil.particles(e, ParticleTypes.LAVA, e.position().add(0, 1, 0), 20, 1.5, 0.6, 1.5, 0.1);
                FpeUtil.sound(e, SoundEvents.GENERIC_EXPLODE, 0.9f, 1.3f);
            }
        }));
        // 4. claw glove: horizontal rake (9) + overhead rake (17)
        out.add(Ability.of("claw", 30, 40).range(0, 4).weight(4).faceUntil(16).tick((e, t, tk) -> {
            if (tk == 9 || tk == 17) {
                e.dashForward(0.35, 0);
                for (LivingEntity v : FpeCombat.cone(e, 3.8, 60)) { v.invulnerableTime = 0; FpeUtil.hit(e, v, e.dmg(tk == 9 ? 0.9f : 1.2f), 0.7, 0.25); FpeCombat.bleed(e, v, 40); }
                FpeCombat.slashArc(e, 3.8f, 110, tk == 9 ? 15 : 80, 0, 1.4, 0xE0302838);
                FpeUtil.sound(e, SoundEvents.PLAYER_ATTACK_SWEEP, 1f, 0.7f);
            }
        }));
        // 5. spin and lash with the floor-length hair (14, 20)
        out.add(Ability.of("hair_whip", 32, 60).range(0, 6).weight(3).faceUntil(8).tick((e, t, tk) -> {
            if (tk == 14 || tk == 20) {
                FpeUtil.hitRadius(e, e.position(), 5.0, e.dmg(0.9f), 1.2, 0.3);
                FpeUtil.arc(e, ParticleTypes.SWEEP_ATTACK, e.position().add(0, 1.0, 0), tk * 15f, 180, 3.8, 8);
                FpeUtil.sound(e, SoundEvents.PLAYER_ATTACK_SWEEP, 1.2f, 0.5f);
            }
        }));
        // 6. flamethrower aimed backwards as a jet: rocket-propelled claw charge (20..36)
        out.add(Ability.of("flame_rush", 52, 110).range(6, 18).weight(4).moving().faceUntil(19).tick((e, t, tk) -> {
            Vec3 back = FpeUtil.forward(e).scale(-1);
            if (tk < 18 && tk % 4 == 2) {
                FpeUtil.particles(e, ParticleTypes.FLAME, nozzle(e, -0.6), 6, 0.2, 0.1, 0.2, 0.05);
                FpeUtil.sound(e, SoundEvents.BLAZE_SHOOT, 0.4f, 0.5f);
            }
            if (tk >= 20 && tk <= 36) {
                e.dashForward(1.2, 0);
                jet(e, e.position().add(0, 0.9, 0).add(back.scale(0.8)), back, 3);
                FpeUtil.particles(e, ParticleTypes.LARGE_SMOKE, e.position().add(0, 0.4, 0), 2, 0.3, 0.1, 0.3, 0.02);
                for (LivingEntity v : FpeUtil.enemiesInRadius(e, FpeUtil.ahead(e, 1.2, 0), 1.9, 2.5, 0.5))
                    if (FpeUtil.hit(e, v, e.dmg(0.9f), 1.4, 0.45)) v.setSecondsOnFire(3);
                if (tk % 4 == 0) FpeUtil.sound(e, SoundEvents.FIRECHARGE_USE, 0.6f, 0.6f);
            }
        }));
        // 7. molotov: bottle lit on the pilot light, thrown at 14 -> burning circle at the target's feet
        out.add(Ability.of("molotov", 46, 80).range(5, 16).weight(3).faceUntil(12).tick((e, t, tk) -> {
            if (tk == 6) FpeUtil.particles(e, ParticleTypes.FLAME, e.position().add(0, 1.3, 0).add(FpeUtil.forward(e).scale(0.6)), 6, 0.1, 0.1, 0.1, 0.01);
            if (tk == 14) {
                FpeUtil.fx(e, FpeFx.Kind.RING_TRAP, t.position().add(0, 0.05, 0), 24, 34, 3.6f, e.dmg(1.2f)).color(0xFFFF6A20);
                FpeUtil.sound(e, SoundEvents.SPLASH_POTION_THROW, 1f, 0.7f);
                FpeUtil.particles(e, ParticleTypes.FLAME, t.position().add(0, 0.2, 0), 10, 1.2, 0.1, 1.2, 0.02);
            }
            if (tk == 38) burnRadius(e, t.position(), 3.8, 0, 0, 7);
        }));
        // 8. ENRAGED "I am the FIRE!": gun to the sky, four expanding fire pulses (20/34/48/62)
        out.add(Ability.of("inferno", 74, 200).range(0, 14).weight(6).blind().when(FpeEntity::isEnraged).faceUntil(10).tick((e, t, tk) -> {
            if (tk >= 18 && tk <= 64) FpeUtil.particles(e, ParticleTypes.FLAME, e.position().add(0, 3.2, 0), 4, 0.3, 0.6, 0.3, 0.04);
            if (tk >= 20 && tk <= 62 && tk % 14 == 6) {
                FpeUtil.fx(e, FpeFx.Kind.RING_SHOCK, e.position().add(0, 0.1, 0), 0, 18, 12f, 0).color(0xFFFF7020);
                FpeUtil.sound(e, SoundEvents.BLAZE_SHOOT, 1.2f, 0.5f);
            }
            if (tk >= 20 && tk <= 66 && tk % 6 == 0) {
                double r = 2 + (tk - 20) * 0.22;
                FpeUtil.arc(e, ParticleTypes.FLAME, e.position().add(0, 0.2, 0), 0, 180, r, 36);
                FpeUtil.arc(e, ParticleTypes.LARGE_SMOKE, e.position().add(0, 1.2, 0), 0, 180, r, 18);
                for (LivingEntity v : FpeUtil.enemiesInRadius(e, e.position(), r + 1.5, 3, 1))
                    if (FpeUtil.hit(e, v, e.dmg(0.7f), 0.8, 0.3)) v.setSecondsOnFire(5);
            }
        }));
        // 9. low sweep across the ground (12..24) leaves a wall of flame between her and the target
        out.add(Ability.of("fire_wall", 44, 100).range(3, 12).weight(3).faceUntil(11).tick((e, t, tk) -> {
            if (tk >= 12 && tk <= 24) {
                double off = 50 - (tk - 12) * (100 / 12.0);      // sweeps character's right -> left (rotY + = toward her right)
                Vec3 d = yawDir(e, off);
                jet(e, nozzle(e, 1.0).add(0, -0.8, 0), d, 3.5);
                if (tk % 3 == 0) {
                    Vec3 spot = e.position().add(d.scale(3.4));
                    FpeUtil.fx(e, FpeFx.Kind.RING_TRAP, spot.add(0, 0.05, 0), 10 + (24 - tk) / 2, 30, 1.3f, e.dmg(0.9f)).color(0xFFFF7020);
                }
                if (tk % 4 == 0) { burnCone(e, 5, 30, e.dmg(0.4f), 3); FpeUtil.sound(e, SoundEvents.BLAZE_SHOOT, 0.6f, 0.6f); }
            }
            if (tk > 24 && tk % 4 == 0) for (int i = -2; i <= 2; i++)
                FpeUtil.particles(e, ParticleTypes.FLAME, e.position().add(yawDir(e, i * 22).scale(3.4)), 4, 0.4, 0.4, 0.4, 0.01);
        }));
        // 10. napalm rain: four gouts fired into the sky (14/17/20/23), they fall around the target ~1s later
        out.add(Ability.of("napalm_rain", 50, 120).range(6, 20).weight(3).faceUntil(12).tick((e, t, tk) -> {
            if (tk == 14 || tk == 17 || tk == 20 || tk == 23) {
                FpeUtil.particles(e, ParticleTypes.FLAME, e.position().add(0, 3.0, 0), 20, 0.3, 1.0, 0.3, 0.12);
                FpeUtil.sound(e, SoundEvents.FIRECHARGE_USE, 1f, 0.6f);
                int n = (tk - 14) / 3;
                Vec3 off = n == 0 ? Vec3.ZERO : FpeCombat.rotY(new Vec3(0, 0, 2.6), n * 120 + e.getRandom().nextInt(40));
                Vec3 spot = t.position().add(t.getDeltaMovement().scale(6)).add(off);
                FpeUtil.fx(e, FpeFx.Kind.RING_TRAP, spot.add(0, 0.05, 0), 20, 30, 2.2f, e.dmg(1.1f)).color(0xFFFF5A18);
                FpeUtil.particles(e, ParticleTypes.LAVA, spot.add(0, 6, 0), 4, 0.5, 0.5, 0.5, 0.1);
            }
        }));
        // 11. wolf pounce: crouch, leap (9), claw slam on landing (17)
        out.add(Ability.of("pounce", 36, 70).range(4, 10).weight(3).moving().faceUntil(9).tick((e, t, tk) -> {
            if (tk == 9) {
                e.dashToward(t.position(), Math.min(1.6, e.distanceTo(t) * 0.2), 0.45);
                FpeUtil.sound(e, SoundEvents.WOLF_GROWL, 1f, 1.2f);
            }
            if (tk == 17) {
                burnRadius(e, FpeUtil.ahead(e, 1.0, 0), 2.6, e.dmg(1.4f), 0.9, 3);
                FpeCombat.slashArc(e, 2.8f, 120, 85, 0, 0.6, 0xE0302838);
                FpeUtil.arc(e, ParticleTypes.FLAME, FpeUtil.ahead(e, 1.0, 0.2), 0, 180, 1.8, 20);
                FpeUtil.sound(e, SoundEvents.GENERIC_EXPLODE, 0.6f, 1.5f);
            }
        }));
        // 12. ENRAGED pyre spin: flamethrower held out, two full turns of fire (14..44)
        out.add(Ability.of("pyre_spin", 60, 160).range(0, 7).weight(5).blind().when(FpeEntity::isEnraged).faceUntil(12).tick((e, t, tk) -> {
            if (tk >= 14 && tk <= 44) {
                double yaw = (tk - 14) * 24.0;        // matches anim: 360 deg per 15 ticks, turning right
                Vec3 d = FpeCombat.rotY(FpeUtil.right(e).scale(-1), yaw);
                jet(e, e.position().add(0, 1.4, 0).add(d.scale(0.9)), d, 4.5);
                if (tk % 4 == 2) {
                    burnRadius(e, e.position(), 5.5, e.dmg(0.6f), 0.7, 4);
                    FpeUtil.sound(e, SoundEvents.BLAZE_SHOOT, 0.8f, 0.6f);
                }
            }
            if (tk == 44) e.addEffect(new MobEffectInstance(MobEffects.MOVEMENT_SPEED, 60, 1, false, false));
        }));
    }
}
